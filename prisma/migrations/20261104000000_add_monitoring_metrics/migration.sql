-- Add current resource metrics to devices and heartbeat history.
ALTER TABLE "Device"
  ADD COLUMN IF NOT EXISTS "ramUsagePct" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "ramUsedGB" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "ramTotalGB" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "diskUsagePct" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "diskFreeGB" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "diskTotalGB" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "latencyMs" INTEGER;

ALTER TABLE "Heartbeat"
  ADD COLUMN IF NOT EXISTS "ramUsagePct" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "diskFreeGB" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "latencyMs" INTEGER;
